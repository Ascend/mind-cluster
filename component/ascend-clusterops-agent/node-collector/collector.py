# Commands allowed to run on the node. A command is run only when its whitespace-normalized
# string matches one of these strings exactly.
ALLOWED_COMMANDS = frozenset(
    {
        "/usr/bin/dmesg -T | tail -n 100000 > dmesg",
        "/usr/sbin/dmidecode > dmidecode.txt",
        "/usr/bin/msnpureport --docker",
    }
)


def _cmd_allowed(cmd: str) -> bool:
    """Whole-string whitelist check: the command (whitespace-collapsed) must match exactly."""
    return " ".join(cmd.split()) in ALLOWED_COMMANDS


