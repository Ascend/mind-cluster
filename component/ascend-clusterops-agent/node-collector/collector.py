"""node-collector: runs on the NPU worker node (DaemonSet).

Collects according to collect_manifest.yaml (v3/entities), organizes the output into the
directory layout expected by ascend-fd parse, runs ascend-fd parse locally, then tars the
cleaned artifacts and actively reports them to the agent via gRPC UploadResult.

Mount paths are resolved by the collector-local pod -> host_paths table (pathmap, sourced
from the global CM), not dispatched by the agent. During diagnosis the agent queries the
central relation table by jobname for all pods -> nodes, and dispatches
TriggerCollect {node, job, pods:[{pod_uid,ns,name}]} to each node; the collector then
collects + cleans in the background and reports the result via UploadResult (failures are
also reported). Asynchronous model: the agent keeps no long-lived connections.

Collect contract field priority (executed by _gather):
  env          : highest. Read the pod env value (in-container path, recorded by agent-core
                 in the pathmap CM) -> reverse-lookup the host path via pathmap -> copy to
                 {collect_dir}/name. When it succeeds, paths/commands/mount_keywords are
                 skipped; on failure (value not recorded / not resolvable) the lower-priority
                 fields run.
  paths        : equal priority with commands. In-pod path -> match the pod mount pairs by
                 container path -> reverse-lookup the host path -> copy (fall back to reading
                 the host paths directly when no mount pair matches). dl_log/host_log paths
                 are node host paths read directly without pathmap.
  commands     : equal priority with paths. Run whitelisted commands in a temp dir (shell) ->
                 copy all generated files to {collect_dir}/name -> clean up the temp dir;
                 commands without a > redirect capture stdout/stderr as {name}_stdout.txt.
                 The WHOLE command string must exactly match the ALLOWED_COMMANDS whitelist
                 (dmesg/dmidecode/msnpureport invocations); tampered strings are skipped.
  mount_keywords : lowest (used only when paths is not configured, e.g. an entity with env
                 configured but the pod lookup finds no value). Match mount pairs by keyword
                 (first hit wins); if no direct hit, scan the mount host path subdirectories
                 for a subdir containing the keyword
"""

