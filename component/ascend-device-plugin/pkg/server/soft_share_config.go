const (
	// minSoftShareCoreQuota is the minimum accepted AI Core percentage.
	minSoftShareCoreQuota = 1
	// maxSoftShareCoreQuota is the maximum accepted AI Core percentage.
	maxSoftShareCoreQuota = 100
	// fixedSharePolicy is the manager policy requiring a positive HBM reservation.
	fixedSharePolicy = 1
)

// SoftShareCreateInput contains the scheduling inputs for one manager allocation.
type SoftShareCreateInput struct {
	pod          *v1.Pod
	resourceName v1.ResourceName
	physicalID   int
	dieID        string
	annotations  softShareDevAnnotations
}

// allocationEnsurer obtains a manager allocation matching the requested Pod resources.
type allocationEnsurer interface {
	EnsureAllocation(context.Context, enpumanager.AllocateRequest) (*enpuconfig.AllocationResult, error)
}

// EnpuConfigProvider obtains the configuration generated by enpu-manager.
type EnpuConfigProvider struct {
	client allocationEnsurer
}

// GetConfigDir validates scheduling inputs and returns the manager configuration directory.
func (p *EnpuConfigProvider) GetConfigDir(ctx context.Context, input SoftShareCreateInput) (string, error) {
	annotations := input.annotations
	coreQuota, err := strconv.Atoi(annotations.aicoreQuota)
	if err != nil || coreQuota < minSoftShareCoreQuota || coreQuota > maxSoftShareCoreQuota {
		return "", fmt.Errorf("invalid soft share AI Core quota")
	}
	hbmQuota, err := strconv.Atoi(annotations.hbmQuota)
	if err != nil {
		return "", fmt.Errorf("invalid soft share HBM quota: %w", err)
	}
	policy, err := strconv.Atoi(annotations.schedulingPolicy)
	if err != nil {
		return "", fmt.Errorf("invalid soft share scheduling policy")
	}
	if hbmQuota < 0 || (policy == fixedSharePolicy && hbmQuota == 0) {
		return "", fmt.Errorf("invalid HBM quota for soft share scheduling policy %d", policy)
	}
	containerName, err := softShareContainerName(input.pod, input.resourceName)
	if err != nil {
		return "", err
	}
	ctx, cancel := context.WithTimeout(ctx, managerRequestTimeout)
	defer cancel()
	allocation, err := p.client.EnsureAllocation(ctx, enpumanager.AllocateRequest{
		PhysicalID: input.physicalID, PodUID: string(input.pod.UID), AICoreQuota: coreQuota,
		HBMQuota: hbmQuota, SchedPolicy: policy, ContainerName: containerName,
	})
	if err != nil {
		return "", err
	}
	action := "created"
	if allocation.Reused {
		action = "reused"
	}
	hwlog.RunLog.Infof("enpu-manager allocation %s: pod=%s/%s pod_uid=%s allocation_id=%s phy_id=%d vnpu_id=%d",
		action, input.pod.Namespace, input.pod.Name, input.pod.UID, allocation.AllocationID, allocation.PhysicalID, allocation.VirtualID)
	configPath, err := enpuconfig.CleanConfigPath(enpuconfig.ConfigRoot, allocation.ConfigPath)
	if err != nil {
		return "", err
	}
	shmID := allocation.ShmID
	if shmID == "" {
		shmID = allocation.DieID
	}
	if shmID != input.dieID {
		return "", fmt.Errorf("enpu-manager shared memory ID %q does not match device die ID %q", shmID, input.dieID)
	}
	if path.Base(configPath) != api.SoftShareDeviceConfigFileName {
		return "", fmt.Errorf("unexpected soft share configuration filename %q", path.Base(configPath))
	}
	return path.Dir(configPath), nil
}

// softShareContainerName finds the unique container requesting the selected NPU resource.
func softShareContainerName(pod *v1.Pod, resourceName v1.ResourceName) (string, error) {
	var name string
	for _, containers := range [][]v1.Container{pod.Spec.Containers, pod.Spec.InitContainers} {
		for _, container := range containers {
			request := container.Resources.Requests[resourceName]
			limit := container.Resources.Limits[resourceName]
			if request.Sign() <= 0 && limit.Sign() <= 0 {
				continue
			}
			if name != "" {
				return "", fmt.Errorf("multiple containers in Pod %s request NPU resource %s", pod.UID, resourceName)
			}
			name = container.Name
		}
	}
	if name == "" {
		return "", fmt.Errorf("no container in Pod %s requests NPU resource %s", pod.UID, resourceName)
	}
	return name, nil
}

// getManagerNPUInfoConfigDir reconciles stale allocations and obtains the manager configuration directory.
func (ps *PluginServer) getManagerNPUInfoConfigDir(pod *v1.Pod, devices []string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), managerRequestTimeout)
	defer cancel()
	physicalID, err := ps.getValidLogicDeviceID(devices)
	if err != nil {
		return "", err
	}
	annotations, err := ps.extractPodAnnotations(pod)
	if err != nil {
		return "", err
	}
	dieID, err := ps.getDieIDFromPhysicID(physicalID)
	if err != nil {
		return "", err
	}
	// Reconcile stale allocations before creating a new one. This is best-effort hygiene:
	// right after start the Pod cache is not synchronized yet, and a failed reconcile round
	// only affects release, so it must not block creation. A manager connection failure
	// still exits the process through managerOperationError.
	if err := ps.softShareManager.reconcileAllocations(ctx, ps.manager.GetKubeClient()); err != nil && ctx.Err() == nil {
		_ = managerOperationError(err)
		hwlog.RunLog.Warnf("skip stale allocation reconcile before creating soft share configuration: %v", err)
	}
	ps.softShareManager.allocationLock.Lock()
	defer ps.softShareManager.allocationLock.Unlock()
	if err := ctx.Err(); err != nil {
		return "", err
	}
	directory, err := ps.enpuProvider.GetConfigDir(ctx, SoftShareCreateInput{
		pod: pod, resourceName: v1.ResourceName(ps.resourceName()), physicalID: physicalID,
		dieID: dieID, annotations: annotations,
	})
	if err != nil {
		return "", managerOperationError(err)
	}
	return directory, nil
}
